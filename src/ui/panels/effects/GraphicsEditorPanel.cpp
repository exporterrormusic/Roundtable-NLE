void GraphicsEditorPanel::setClip(Clip* clip, Track* track)
{
 const bool editable = rt::canMutateClip(clip, track);
 if (m_splitter) m_splitter->setEnabled(editable);
 if (m_clip == clip) {
 m_track = track;
 return;
 }
 m_clip = clip;
 m_track = track;
 m_clipId = clip ? clip->id() : 0;
 m_graphicClip = nullptr;
 m_selectedLayer = nullptr;
 m_selectedLayerIdx = -1;

 clearEditControls();
 m_layerList->clear();

 if (clip && clip->clipType() == ClipType::Graphic) {
 m_graphicClip = static_cast<GraphicClip*>(clip);
 m_clipNameLabel->setText(QString::fromStdString(clip->label()));

 // Show type badge
 const QColor badgeColor(220, 140, 60); // Graphic = orange
 m_typeBadge->setText(tr("Graphic"));
 m_typeBadge->setStyleSheet(QStringLiteral(
 "font-size: 11px; font-weight: 600; padding: 0 6px; border-radius: 3px; "
 "color: %1; background: %2;")
 .arg(Theme::hex(badgeColor.lighter(180)),
 Theme::hex(badgeColor.darker(200))));
 m_typeBadge->setVisible(true);

 // Show content, hide empty state
 m_splitter->setVisible(true);
 if (m_emptyLabel) m_emptyLabel->setVisible(false);

 rebuildLayerList();
 // Auto-select topmost layer
 if (m_graphicClip->layerCount() > 0) {
 m_layerList->setCurrentRow(0); // list is reverse stack order
 }
 } else {
 m_clipNameLabel->setText(tr("Graphics Editor"));
 m_typeBadge->setVisible(false);
 m_splitter->setVisible(false);
 if (m_emptyLabel) m_emptyLabel->setVisible(true);
 if (m_statusLabel) m_statusLabel->setText(tr("No clip"));
 }
}

void GraphicsEditorPanel::setTimeline(Timeline* timeline) noexcept
{
 if (m_timeline != timeline) clearClip();
 m_timeline = timeline;
}

bool GraphicsEditorPanel::resolveBoundClip() noexcept
{
 if (!m_timeline) {
     if (!m_clip || !m_track || m_clip->clipType() != ClipType::Graphic
         || !rt::canMutateClip(m_clip, m_track))
         return false;
     m_graphicClip = static_cast<GraphicClip*>(m_clip);
     return true;
 }
 Track* track = nullptr;
 Clip* clip = rt::resolveClipById(m_timeline, m_clipId, &track);
 if (!clip || clip->clipType() != ClipType::Graphic) {
     m_clip = nullptr;
     m_track = nullptr;
     m_graphicClip = nullptr;
     m_selectedLayer = nullptr;
     m_selectedLayerIdx = -1;
     return false;
 }
 m_clip = clip;
 m_track = track;
 m_graphicClip = static_cast<GraphicClip*>(clip);
 if (m_selectedLayerIdx >= 0
     && m_selectedLayerIdx < static_cast<int>(m_graphicClip->layerCount()))
     m_selectedLayer = m_graphicClip->layer(static_cast<size_t>(m_selectedLayerIdx));
 else
     m_selectedLayer = nullptr;
 return true;
}

bool GraphicsEditorPanel::canMutateBoundClip() noexcept
{
 return resolveBoundClip() && !m_track->isLocked();
}

void GraphicsEditorPanel::refresh()
{
 if (!resolveBoundClip()) { clearClip(); return; }
 if (m_selectedLayer) populateFromLayer();
}

void GraphicsEditorPanel::clearClip()
{
 m_clip = nullptr;
 m_track = nullptr;
 m_graphicClip = nullptr;
 m_selectedLayer = nullptr;
 m_selectedLayerIdx = -1;
 m_clipId = 0;
 clearEditControls();
 m_layerList->clear();
 m_clipNameLabel->setText(tr("Graphics Editor"));
 m_typeBadge->setVisible(false);
 m_splitter->setVisible(false);
 if (m_emptyLabel) m_emptyLabel->setVisible(true);
 if (m_statusLabel) m_statusLabel->setText(tr("No clip"));
}

