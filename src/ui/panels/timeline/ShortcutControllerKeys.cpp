// keyReleaseEvent — needed only for Premiere-style K+J / K+L slow scrub.
// Releasing J or L while the slow shuttle is engaged must stop playback;
// the regular J/L (no K) ramp is unaffected and stays running until K or
// space is pressed.
// ─────────────────────────────────────────────────────────────────────────────
void ShortcutController::handleKeyRelease(QKeyEvent* event)
{
    if (event->isAutoRepeat()) { event->ignore(); return; }

    QWidget* fw = QApplication::focusWidget();
    auto* ctl = (m_ws->sourceMonitor() && m_ws->sourceMonitor()->controller()
                 && m_ws->sourceMonitor()->hasClip() && fw
                 && (fw == m_ws->sourceMonitor() || m_ws->sourceMonitor()->isAncestorOf(fw)))
        ? m_ws->sourceMonitor()->controller()
        : m_ws->playbackController();

    const int key = event->key();
    if (key == Qt::Key_K) {
        m_kHeld = false;
        if (m_kSlowShuttleActive) {
            if (ctl) ctl->shuttlePause();
            m_kSlowShuttleActive = false;
        }
        event->accept(); return;
    }
    if ((key == Qt::Key_J || key == Qt::Key_L) && m_kSlowShuttleActive) {
        if (ctl) ctl->shuttlePause();
        m_kSlowShuttleActive = false;
        event->accept(); return;
    }

    event->ignore();
}

